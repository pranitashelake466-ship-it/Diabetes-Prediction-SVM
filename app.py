
import streamlit as st
import numpy as np
import pandas as pd
import joblib

# Load trained SVM pipeline
model = joblib.load("diabetes_svm_model.pkl")

# Page configuration
st.set_page_config(
    page_title="Diabetes Prediction System",
    page_icon="🩺",
    layout="wide"
)

# Header
st.title("Diabetes Prediction System")
st.write(
    "A Machine Learning application using "
    "Support Vector Machine (SVM)."
)

st.divider()

st.subheader("Enter Patient Information")

# Input fields
col1, col2 = st.columns(2)

with col1:
    pregnancies = st.number_input(
        "Pregnancies",
        min_value=0,
        max_value=20,
        value=1
    )

    glucose = st.number_input(
        "Glucose Level",
        min_value=0.0,
        max_value=300.0,
        value=120.0
    )

    blood_pressure = st.number_input(
        "Blood Pressure",
        min_value=0.0,
        max_value=200.0,
        value=70.0
    )

    skin_thickness = st.number_input(
        "Skin Thickness",
        min_value=0.0,
        max_value=100.0,
        value=20.0
    )

with col2:
    insulin = st.number_input(
        "Insulin Level",
        min_value=0.0,
        max_value=900.0,
        value=80.0
    )

    bmi = st.number_input(
        "BMI",
        min_value=0.0,
        max_value=100.0,
        value=25.0
    )

    diabetes_pedigree = st.number_input(
        "Diabetes Pedigree Function",
        min_value=0.0,
        max_value=3.0,
        value=0.5
    )

    age = st.number_input(
        "Age",
        min_value=1,
        max_value=120,
        value=30
    )

st.divider()

# Prediction
if st.button("Predict Diabetes", type="primary"):

    input_data = pd.DataFrame(
        [[
            pregnancies,
            glucose,
            blood_pressure,
            skin_thickness,
            insulin,
            bmi,
            diabetes_pedigree,
            age
        ]],
        columns=[
            "Pregnancies",
            "Glucose",
            "BloodPressure",
            "SkinThickness",
            "Insulin",
            "BMI",
            "DiabetesPedigreeFunction",
            "Age"
        ]
    )

    prediction = model.predict(input_data)[0]

    st.subheader("Prediction Result")

    if prediction == 1:
        st.error(
            "The model predicts a higher likelihood "
            "of diabetes."
        )
    else:
        st.success(
            "The model predicts a lower likelihood "
            "of diabetes."
        )

    st.info(
        "This result is generated by a machine learning "
        "model and is not a medical diagnosis. "
        "Consult a qualified healthcare professional."
    )

st.divider()

st.caption(
    "Developed as an academic Machine Learning project "
    "using Python, Streamlit and SVM."
)
